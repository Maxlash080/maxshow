export const MAHARASHTRA_CITIES = Object.keys(MAHARASHTRA_CITIES_DATA).sort((a, b) => a.localeCompare(b));

export const getCustomAreasForCity = (cityName) => {
  try {
    const raw = localStorage.getItem(`MAXSHOW_CUSTOM_AREAS_${cityName || 'Pune'}`);
    return raw ? JSON.parse(raw) : [];
  } catch (_) {
    return [];
  }
};

export const saveCustomAreaForCity = (cityName, newArea) => {
  if (!newArea || !cityName) return;
  try {
    const current = getCustomAreasForCity(cityName);
    if (!current.some((a) => a.toLowerCase() === newArea.toLowerCase())) {
      const updated = [...current, newArea];
      localStorage.setItem(`MAXSHOW_CUSTOM_AREAS_${cityName}`, JSON.stringify(updated));
    }
  } catch (_) {}
};

export const getAreasForCity = (cityName = 'Pune') => {
  const cityKey = MAHARASHTRA_CITIES.find(
    (c) => c.toLowerCase() === (cityName || '').toLowerCase()
  ) || 'Pune';

  const defaultAreas = MAHARASHTRA_CITIES_DATA[cityKey] || MAHARASHTRA_CITIES_DATA['Pune'] || [];
  const customAreas = getCustomAreasForCity(cityKey);
  const combined = Array.from(new Set([...defaultAreas, ...customAreas]));
  return combined.sort((a, b) => a.localeCompare(b));
};

export const parseLocationCityAndArea = (rawLocation) => {
  if (!rawLocation || typeof rawLocation !== 'string') {
    return { city: 'Pune', area: '' };
  }
  const clean = rawLocation.trim();
  if (clean.includes(',')) {
    const parts = clean.split(',').map((p) => p.trim()).filter(Boolean);

    // Check if the last part is a recognized city (e.g. "Hinjawadi, Pune")
    const lastPart = parts[parts.length - 1];
    const matchedCityLast = MAHARASHTRA_CITIES.find(
      (c) => c.toLowerCase() === lastPart.toLowerCase() || c.toLowerCase().includes(lastPart.toLowerCase())
    );
    if (matchedCityLast) {
      const remainingArea = parts.slice(0, parts.length - 1).join(', ').trim();
      return {
        city: matchedCityLast,
        area: remainingArea,
      };
    }

    // Check if the first part is a recognized city (e.g. "Pune, Hinjawadi")
    const firstPart = parts[0];
    const matchedCityFirst = MAHARASHTRA_CITIES.find(
      (c) => c.toLowerCase() === firstPart.toLowerCase() || c.toLowerCase().includes(firstPart.toLowerCase())
    );
    if (matchedCityFirst) {
      const remainingArea = parts.slice(1).join(', ').trim();
      return {
        city: matchedCityFirst,
        area: remainingArea,
      };
    }
  }

  // Check if rawLocation matches any known city directly
  const directCity = MAHARASHTRA_CITIES.find(
    (c) => c.toLowerCase() === clean.toLowerCase()
  );
  if (directCity) {
    return { city: directCity, area: '' };
  }

  // Search if area belongs to any known city
  for (const [cName, areaList] of Object.entries(MAHARASHTRA_CITIES_DATA)) {
    if (areaList.some((a) => a.toLowerCase() === clean.toLowerCase())) {
      return { city: cName, area: clean };
    }
  }

  return { city: 'Pune', area: clean };
};

export const formatCityAndArea = (city, area) => {
  const cleanCity = (city || 'Pune').trim();
  const cleanArea = (area || '').trim();
  if (cleanCity && cleanArea) {
    return `${cleanCity}, ${cleanArea}`;
  }
  return cleanCity || cleanArea || 'Pune';
};

export const formatLocationString = (area, city) => {
  const cleanArea = (area || '').trim();
  const cleanCity = (city || 'Pune').trim();
  if (!cleanArea) return cleanCity;
  if (cleanArea.toLowerCase().endsWith(cleanCity.toLowerCase())) {
    return cleanArea;
  }
  return `${cleanArea}, ${cleanCity}`;
};

