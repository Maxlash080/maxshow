/**
 * Storage helpers for user-added custom cities per state
 */
export const getCustomCitiesForState = (stateName) => {
  if (!stateName) return [];
  try {
    const raw = localStorage.getItem(`MAXSHOW_CUSTOM_CITIES_${stateName.trim()}`);
    return raw ? JSON.parse(raw) : [];
  } catch (_) {
    return [];
  }
};

export const saveCustomCityForState = (stateName, newCity) => {
  if (!newCity || !stateName) return;
  try {
    const cleanCity = newCity.trim();
    const cleanState = stateName.trim();
    const current = getCustomCitiesForState(cleanState);
    if (!current.some((c) => c.toLowerCase() === cleanCity.toLowerCase())) {
      const updated = [...current, cleanCity];
      localStorage.setItem(`MAXSHOW_CUSTOM_CITIES_${cleanState}`, JSON.stringify(updated));
    }
  } catch (_) {}
};

export const getCitiesForState = (stateName = 'Maharashtra') => {
  if (!stateName || typeof stateName !== 'string') {
    return INDIAN_STATES_DATA['Maharashtra'] || [];
  }
  const clean = stateName.trim().toLowerCase();

  // 1. Exact match (case-insensitive)
  let stateKey = INDIAN_STATES.find((s) => s.toLowerCase() === clean);

  // 2. Partial match (e.g. "Delhi" matches "Delhi (NCT)")
  if (!stateKey) {
    stateKey = INDIAN_STATES.find(
      (s) => s.toLowerCase().startsWith(clean) || clean.startsWith(s.toLowerCase()) || s.toLowerCase().includes(clean)
    );
  }

  // 3. Fallback
  if (!stateKey) {
    stateKey = 'Maharashtra';
  }

  const defaultCities = INDIAN_STATES_DATA[stateKey] || [];
  const customCities = getCustomCitiesForState(stateKey);
  const combined = Array.from(new Set([...defaultCities, ...customCities]));
  return combined.sort((a, b) => a.localeCompare(b));
};

/**
 * Parse a raw location string into { state, city }
 */
export const parseLocationStateAndCity = (rawLocation) => {
  if (!rawLocation || typeof rawLocation !== 'string') {
    return { state: 'Maharashtra', city: 'Pune' };
  }
  const clean = rawLocation.trim();
  if (clean.includes(',')) {
    const parts = clean.split(',').map((p) => p.trim()).filter(Boolean);

    // Format 1: "City, State" (e.g. "Pune, Maharashtra" or "Bengaluru, Karnataka")
    const lastPart = parts[parts.length - 1];
    const matchedStateLast = INDIAN_STATES.find(
      (s) => s.toLowerCase() === lastPart.toLowerCase() || s.toLowerCase().includes(lastPart.toLowerCase())
    );
    if (matchedStateLast) {
      const remainingCity = parts.slice(0, parts.length - 1).join(', ').trim();
      return {
        state: matchedStateLast,
        city: remainingCity || (INDIAN_STATES_DATA[matchedStateLast]?.[0] || 'Pune'),
      };
    }

    // Format 2: "State, City"
    const firstPart = parts[0];
    const matchedStateFirst = INDIAN_STATES.find(
      (s) => s.toLowerCase() === firstPart.toLowerCase() || s.toLowerCase().includes(firstPart.toLowerCase())
    );
    if (matchedStateFirst) {
      const remainingCity = parts.slice(1).join(', ').trim();
      return {
        state: matchedStateFirst,
        city: remainingCity || (INDIAN_STATES_DATA[matchedStateFirst]?.[0] || 'Pune'),
      };
    }

    // Format 3: Legacy "Area, City" (e.g. "Hinjawadi, Pune" or "Kasarwadi, Pune")
    for (const [stName, cityList] of Object.entries(INDIAN_STATES_DATA)) {
      const foundCity = cityList.find(
        (c) => c.toLowerCase() === lastPart.toLowerCase() || c.toLowerCase().includes(lastPart.toLowerCase())
      );
      if (foundCity) {
        return {
          state: stName,
          city: parts[0] || foundCity,
        };
      }
    }
  }

  // Direct check if clean matches a state directly
  const directState = INDIAN_STATES.find(
    (s) => s.toLowerCase() === clean.toLowerCase()
  );
  if (directState) {
    return { state: directState, city: INDIAN_STATES_DATA[directState]?.[0] || 'Pune' };
  }

  // Direct check if clean matches any known city across all states
  for (const [stName, cityList] of Object.entries(INDIAN_STATES_DATA)) {
    const foundCity = cityList.find(
      (c) => c.toLowerCase() === clean.toLowerCase() || c.toLowerCase().includes(clean.toLowerCase())
    );
    if (foundCity) {
      return { state: stName, city: foundCity };
    }
  }

  return { state: 'Maharashtra', city: clean || 'Pune' };
};

/**
 * Format state and city as <State, City> display / storage string
 */
export const formatLocationString = (city, state) => {
  let cleanCity = (city || 'Pune').trim();
  let cleanState = (state || 'Maharashtra').trim();

  // If first argument passed was state and second was city
  if (
    INDIAN_STATES.some((s) => s.toLowerCase() === cleanCity.toLowerCase()) &&
    !INDIAN_STATES.some((s) => s.toLowerCase() === cleanState.toLowerCase())
  ) {
    const temp = cleanCity;
    cleanCity = cleanState;
    cleanState = temp;
  }

  cleanState = cleanState || 'Maharashtra';
  cleanCity = cleanCity || 'Pune';

  return `${cleanState}, ${cleanCity}`;
};

